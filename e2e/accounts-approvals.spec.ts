import { test, expect, type Page } from '@playwright/test';
import { prisma } from '../lib/db/client';
import { verifyTestEnvironment } from '../lib/db/safety';
import { login } from './helpers';

test('manager registration, approval, correction reviews and session revocation', async ({ page, browser }) => {
  test.setTimeout(180000);
  await verifyTestEnvironment(true);
  const email = `manager-${Date.now()}@example.test`;
  const password = 'Synthetic-manager-123';
  const replacement = 'Synthetic-replacement-456';
  const managerContext = await browser.newContext({ baseURL: 'http://127.0.0.1:3100' });
  const manager = await managerContext.newPage();
  async function signIn(target: Page, secret: string) {
    await target.goto('/login');
    await target.getByLabel('Username', { exact: true }).fill(email);
    await target.getByLabel('Password', { exact: true }).fill(secret);
    await target.getByRole('button', { name: 'Sign In', exact: true }).click();
  }
  try {
    await manager.goto('/register');
    await manager.getByLabel('Full name').fill('Approval Fixture Manager');
    await manager.getByLabel('Email address').fill(email);
    await manager.getByLabel('Password', { exact: true }).fill(password);
    await expect(manager.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
    await manager.getByRole('button', { name: 'Show password', exact: true }).click();
    await expect(manager.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
    await expect(manager.getByLabel('Password', { exact: true })).toHaveValue(password);
    await manager.getByRole('button', { name: 'Hide password', exact: true }).click();
    await expect(manager.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
    await manager.getByRole('button', { name: 'Request access' }).click();
    await expect(manager.getByRole('status')).toContainText(/approve access/i);
    const account = await prisma.staffAccount.findUniqueOrThrow({ where: { email } });
    expect(account.status).toBe('PENDING');
    await signIn(manager, password);
    await expect(manager.getByRole('alert')).toBeVisible();
    await expect(manager).toHaveURL(/\/login/);
    await login(page);
    await page.goto('/staff');
    const row = page.getByRole('row').filter({ hasText: email });
    await row.getByRole('button', { name: 'Approve & Activate' }).click();
    await expect(row).toContainText('Active');
    await signIn(manager, password);
    await expect(manager).toHaveURL(/\/$/);
    expect((await manager.request.get('/api/staff')).status()).toBe(403);
    expect((await manager.request.patch(`/api/staff/${account.id}`, { data: { status: 'ACTIVE' } })).status()).toBe(403);
    await manager.goto('/vehicles/CR93');
    await expect(manager.getByRole('link', { name: /Edit/ }).first()).toBeVisible();
    const original = await prisma.vehicle.findUniqueOrThrow({ where: { id: 'CR93' } });
    await manager.goto('/vehicles/CR93/edit');
    await manager.getByLabel('Model', { exact: true }).fill('Manager correction');
    const submitted = manager.waitForResponse(response => response.request().method() === 'PATCH' && new URL(response.url()).pathname === '/api/vehicles/CR93');
    await manager.getByRole('button', { name: 'Save Changes', exact: true }).click();
    const response = await submitted;
    expect(response.status()).toBe(202);
    const { requestId } = await response.json();
    await expect(manager).toHaveURL(/\/vehicles\/CR93$/);
    expect((await prisma.vehicle.findUniqueOrThrow({ where: { id: 'CR93' } })).model).toBe(original.model);
    expect((await manager.request.post(`/api/approvals/${requestId}`, { data: { approve: true } })).status()).toBe(403);
    await manager.goto('/approvals');
    await expect(manager.getByRole('main').locator(`[data-request-id="${requestId}"]`)).toContainText('PENDING');
    await expect(manager.getByRole('button', { name: 'Approve change' })).toHaveCount(0);
    await page.goto('/approvals');
    const review = page.getByRole('main').locator(`[data-request-id="${requestId}"]`);
    await review.getByText('Review changes', { exact: true }).click();
    await expect(review).toContainText('Manager correction');
    await review.getByRole('button', { name: 'Approve change' }).click();
    await expect(review).toContainText('APPROVED');
    expect((await prisma.vehicle.findUniqueOrThrow({ where: { id: 'CR93' } })).model).toBe('Manager correction');
    const deletion = await manager.request.delete('/api/vehicles/CR93');
    expect(deletion.status()).toBe(202);
    const rejectedId = (await deletion.json()).requestId;
    await page.reload();
    const rejectedReview = page.getByRole('main').locator(`[data-request-id="${rejectedId}"]`);
    await rejectedReview.getByRole('button', { name: 'Reject change' }).click();
    await expect(rejectedReview).toContainText('REJECTED');
    expect((await prisma.vehicle.findUniqueOrThrow({ where: { id: 'CR93' } })).active).toBe(true);
    const created = await manager.request.post('/api/transactions', { data: { vehicleId: 'CR93', date: new Date().toISOString().slice(0, 10), category: 'Income', incomeZarCents: 200000, expenseZarCents: 0, photoUrls: [] } });
    expect(created.status()).toBe(201);
    const transaction = (await created.json()).transaction;
    const transactionEdit = await manager.request.patch(`/api/transactions/${transaction.id}`, { data: { notes: 'Approved accounting correction' } });
    expect(transactionEdit.status()).toBe(202);
    expect((await prisma.transaction.findUniqueOrThrow({ where: { id: transaction.id } })).notes).not.toBe('Approved accounting correction');
    expect((await page.request.post(`/api/approvals/${(await transactionEdit.json()).requestId}`, { data: { approve: true } })).status()).toBe(200);
    expect((await prisma.transaction.findUniqueOrThrow({ where: { id: transaction.id } })).notes).toBe('Approved accounting correction');
    const mileage = await prisma.mileageEntry.findFirstOrThrow({ where: { vehicleId: 'CR91' }, orderBy: { date: 'desc' } });
    const mileageEdit = await manager.request.patch(`/api/mileage/${mileage.id}`, { data: { currentMileageKm: mileage.currentMileageKm + 1 } });
    expect(mileageEdit.status()).toBe(202);
    expect((await page.request.post(`/api/approvals/${(await mileageEdit.json()).requestId}`, { data: { approve: true } })).status()).toBe(200);
    expect((await prisma.mileageEntry.findUniqueOrThrow({ where: { id: mileage.id } })).currentMileageKm).toBe(mileage.currentMileageKm + 1);
    const note = await prisma.vehicleNote.findFirstOrThrow();
    const noteDelete = await manager.request.delete(`/api/notes/${note.id}`);
    expect(noteDelete.status()).toBe(202);
    expect((await page.request.post(`/api/approvals/${(await noteDelete.json()).requestId}`, { data: { approve: false } })).status()).toBe(200);
    expect(await prisma.vehicleNote.findUnique({ where: { id: note.id } })).not.toBeNull();
    await page.goto('/staff');
    await row.getByRole('button', { name: 'Reset Password', exact: true }).click();
    await row.getByPlaceholder('New password (min 12 chars)').fill(replacement);
    await row.getByRole('button', { name: 'Save Password' }).click();
    await expect(row.getByPlaceholder('New password (min 12 chars)')).toHaveCount(0);
    await manager.goto('/transactions');
    await expect(manager).toHaveURL(/\/login/);
    expect((await manager.request.get('/api/vehicles')).status()).toBe(401);
    await signIn(manager, password);
    await expect(manager.getByRole('alert')).toBeVisible();
    await signIn(manager, replacement);
    await expect(manager).toHaveURL(/\/$/);
    await row.getByRole('button', { name: 'Disable', exact: true }).click();
    await expect(row).toContainText('Disabled');
    await manager.goto('/login');
    await expect(manager.getByRole('button', { name: 'Sign In', exact: true })).toBeVisible();
    expect((await manager.request.get('/api/vehicles')).status()).toBe(401);
  } finally { await managerContext.close(); }
});
